import assert from "node:assert/strict";
import fs from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";
import test from "node:test";
const require=createRequire(import.meta.url);
const {configureManifest}=require("../../../plugins/with-play-store-build.js");
type Manifest={ $?:Record<string,string>; "uses-permission"?:{$:Record<string,string>}[] };
const install="android.permission.REQUEST_INSTALL_PACKAGES";

test("switching a generated Play project back to direct APK restores the APK installer capability",()=>{
  const manifest:Manifest={};
  configureManifest(manifest,true);
  assert.equal(manifest["uses-permission"]?.find(p=>p.$["android:name"]===install)?.$["tools:node"],"remove");
  configureManifest(manifest,false);
  assert.ok(!manifest["uses-permission"]?.some(p=>p.$["android:name"]===install&&p.$["tools:node"]==="remove"));
});

test("switching back to Play always removes direct installation permission without touching camera",()=>{
  const manifest:Manifest={"uses-permission":[{$:{"android:name":"android.permission.CAMERA"}}]};
  configureManifest(manifest,false);configureManifest(manifest,true);
  assert.equal(manifest["uses-permission"]?.find(p=>p.$["android:name"]===install)?.$["tools:node"],"remove");
  assert.ok(manifest["uses-permission"]?.some(p=>p.$["android:name"]==="android.permission.CAMERA"&&!p.$["tools:node"]));
});

const {configureSettingsGradle}=require("../../../plugins/with-play-store-build.js");
const mobileRoot=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"../../..");
const silentUpdate="android.permission.UPDATE_PACKAGES_WITHOUT_USER_ACTION";
const installPermissions=[install,silentUpdate];
const removed=(manifest:Manifest,name:string)=>manifest["uses-permission"]?.some(p=>p.$["android:name"]===name&&p.$["tools:node"]==="remove")??false;

test("the Play manifest removes both install permissions and the direct manifest restores them",()=>{
  const manifest:Manifest={"uses-permission":[{$:{"android:name":silentUpdate}}]};
  configureManifest(manifest,true);
  for(const name of installPermissions) assert.ok(removed(manifest,name),`${name} must be removed from Play builds`);
  configureManifest(manifest,false);
  for(const name of installPermissions) assert.ok(!removed(manifest,name),`${name} must not keep a stale remove marker`);
  configureManifest(manifest,true);
  for(const name of installPermissions) assert.equal(manifest["uses-permission"]?.filter(p=>p.$["android:name"]===name).length,1);
});

test("the APK updater module declares the permissions the Play build must strip",()=>{
  const moduleManifest=fs.readFileSync(path.join(mobileRoot,"modules/picket-app-updates/android/src/main/AndroidManifest.xml"),"utf8");
  for(const name of installPermissions) assert.match(moduleManifest,new RegExp(name.replace(/\./g,"\.")));
  assert.match(moduleManifest,/PicketInstallResultReceiver" android:exported="false"/);
});

test("Play Core is linked only through the Play-only module",()=>{
  const playGradle=fs.readFileSync(path.join(mobileRoot,"modules/picket-play-updates/android/build.gradle"),"utf8");
  const apkGradle=fs.readFileSync(path.join(mobileRoot,"modules/picket-app-updates/android/build.gradle"),"utf8");
  assert.match(playGradle,/com\.google\.android\.play:app-update-ktx:/);
  assert.doesNotMatch(apkGradle,/com\.google\.android\.play/);
  const config=JSON.parse(fs.readFileSync(path.join(mobileRoot,"modules/picket-play-updates/expo-module.config.json"),"utf8"));
  assert.deepEqual(config.android.modules,["expo.modules.picketplayupdates.PicketPlayUpdatesModule"]);
});

const freshSettings=`pluginManagement {}

plugins {
  id("com.facebook.react.settings")
  id("expo-autolinking-settings")
}

extensions.configure(com.facebook.react.ReactSettingsExtension) { ex ->
  if (System.getenv('EXPO_USE_COMMUNITY_AUTOLINKING') == '1') {
    ex.autolinkLibrariesFromCommand()
  } else {
    ex.autolinkLibrariesFromCommand(expoAutolinking.rnConfigCommand)
  }
}
expoAutolinking.useExpoModules()
`;
const legacySettings=freshSettings
  .replace(`}\n\nextensions`,`}\n\n// Picket Play build (generated by Expo config plugin)\ndef picketPlayBuild = System.getenv("PICKET_PLAY_BUILD") == "1"\nif (picketPlayBuild) {\n  expoAutolinking.exclude = ["picket-app-updates"]\n}\n\nextensions`)
  .replace("    ex.autolinkLibrariesFromCommand(expoAutolinking.rnConfigCommand)",`    def picketRnConfigCommand = expoAutolinking.rnConfigCommand\n    if (picketPlayBuild) {\n      picketRnConfigCommand = picketRnConfigCommand + ["--exclude", "picket-app-updates"]\n    }\n    ex.autolinkLibrariesFromCommand(picketRnConfigCommand)`);

// Evaluates the generated Groovy ternary for one build, as Gradle would.
function excludedModules(settings:string,playBuild:boolean){
  const match=settings.match(/def picketExcludedModules = picketPlayBuild \? \[([^\]]*)\] : \[([^\]]*)\]/);
  assert.ok(match,"settings.gradle must compute the excluded modules per build");
  return JSON.parse(`[${playBuild?match[1]:match[2]}]`) as string[];
}

function assertChannelExclusions(settings:string){
  assert.deepEqual(excludedModules(settings,true),["picket-app-updates"]);
  assert.deepEqual(excludedModules(settings,false),["picket-play-updates"]);
  assert.match(settings,/expoAutolinking\.exclude = picketExcludedModules/);
  assert.match(settings,/picketExcludedModules\.each \{ picketRnConfigCommand = picketRnConfigCommand \+ \["--exclude", it\] \}/);
  assert.match(settings,/ex\.autolinkLibrariesFromCommand\(picketRnConfigCommand\)/);
  assert.doesNotMatch(settings,/if \(picketPlayBuild\) \{/);
}

test("settings.gradle excludes the APK updater from Play builds and Play Core from direct builds",()=>{
  const settings=configureSettingsGradle(freshSettings);
  assertChannelExclusions(settings);
  assert.equal(configureSettingsGradle(settings),settings);
});

test("a settings.gradle generated by the earlier Play-only plugin is upgraded in place",()=>{
  const upgraded=configureSettingsGradle(legacySettings);
  assertChannelExclusions(upgraded);
  assert.equal(upgraded.match(/Picket Play build/g)?.length,1);
  assert.equal(configureSettingsGradle(upgraded),upgraded);
  const crlf=upgraded.replace(/\n/g,"\r\n");
  assert.equal(configureSettingsGradle(crlf),crlf);
  assertChannelExclusions(configureSettingsGradle(legacySettings.replace(/\n/g,"\r\n")));
});
