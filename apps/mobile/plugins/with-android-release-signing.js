const { withAppBuildGradle } = require("@expo/config-plugins");

const marker = "// Picket release signing (generated by Expo config plugin)";

module.exports = function withAndroidReleaseSigning(config) {
  return withAppBuildGradle(config, (gradleConfig) => {
    if (gradleConfig.modResults.language !== "groovy") return gradleConfig;
    let source = gradleConfig.modResults.contents.replace(/\r\n/g, "\n");
    if (source.includes(marker)) return gradleConfig;

    const androidBlock = "android {";
    if (!source.includes(androidBlock)) {
      throw new Error("Unable to configure Android release signing.");
    }
    source = source.replace(
      androidBlock,
      `${marker}\ndef picketKeystoreProperties = new Properties()\ndef picketKeystorePropertiesFile = rootProject.file('../key.properties')\nif (picketKeystorePropertiesFile.exists()) {\n    picketKeystoreProperties.load(new FileInputStream(picketKeystorePropertiesFile))\n}\n\n${androidBlock}`,
    );

    const signingAnchor = `        debug {\n            storeFile file('debug.keystore')\n            storePassword 'android'\n            keyAlias 'androiddebugkey'\n            keyPassword 'android'\n        }`;
    if (!source.includes(signingAnchor)) {
      throw new Error("Unable to locate Android signingConfigs.debug.");
    }
    source = source.replace(
      signingAnchor,
      `${signingAnchor}\n        if (picketKeystorePropertiesFile.exists()) {\n            release {\n                storeFile file(picketKeystoreProperties['storeFile'])\n                storePassword picketKeystoreProperties['storePassword']\n                keyAlias picketKeystoreProperties['keyAlias']\n                keyPassword picketKeystoreProperties['keyPassword']\n            }\n        }`,
    );

    const buildTypesBlock = source.indexOf("    buildTypes {");
    const releaseBlock = source.indexOf("        release {", buildTypesBlock);
    const releaseSource = source.slice(releaseBlock);
    const signingMatch = releaseSource.match(
      /            signingConfig(?: =)? signingConfigs\.debug/,
    );
    if (buildTypesBlock < 0 || releaseBlock < 0 || !signingMatch) {
      throw new Error("Unable to locate Android release signingConfig.");
    }
    const signingLine = releaseBlock + (signingMatch.index ?? 0);
    const debugReleaseSigning = signingMatch[0];
    source =
      source.slice(0, signingLine) +
      `            if (picketKeystorePropertiesFile.exists()) {\n                signingConfig = signingConfigs.release\n            }` +
      source.slice(signingLine + debugReleaseSigning.length);

    gradleConfig.modResults.contents = source;
    return gradleConfig;
  });
};
