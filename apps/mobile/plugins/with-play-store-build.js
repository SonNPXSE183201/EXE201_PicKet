const { withAndroidManifest, withSettingsGradle, withAppBuildGradle } = require("@expo/config-plugins");

const marker = "// Picket Play build (generated by Expo config plugin)";
const playBuild = process.env.PICKET_PLAY_BUILD === "1";

// Each channel links only its own updater: Play In-App Updates in the AAB, the
// PackageInstaller-based APK updater in direct builds. The choice is made by Gradle
// from PICKET_PLAY_BUILD at build time, so one generated settings.gradle serves both.
const PLAY_ONLY_MODULE = "picket-play-updates";
const DIRECT_ONLY_MODULE = "picket-app-updates";
const settingsBlock = `${marker}
def picketPlayBuild = System.getenv("PICKET_PLAY_BUILD") == "1"
def picketExcludedModules = picketPlayBuild ? ["${DIRECT_ONLY_MODULE}"] : ["${PLAY_ONLY_MODULE}"]
expoAutolinking.exclude = picketExcludedModules`;
const rnCommandBlock = `def picketRnConfigCommand = expoAutolinking.rnConfigCommand
    picketExcludedModules.each { picketRnConfigCommand = picketRnConfigCommand + ["--exclude", it] }
    ex.autolinkLibrariesFromCommand(picketRnConfigCommand)`;
// Written by earlier versions of this plugin (Play exclusion only); upgraded in place
// because prebuild without --clean keeps an existing settings.gradle.
const legacySettingsBlock = `${marker}
def picketPlayBuild = System.getenv("PICKET_PLAY_BUILD") == "1"
if (picketPlayBuild) {
  expoAutolinking.exclude = ["${DIRECT_ONLY_MODULE}"]
}`;
const legacyRnCommandBlock = `def picketRnConfigCommand = expoAutolinking.rnConfigCommand
    if (picketPlayBuild) {
      picketRnConfigCommand = picketRnConfigCommand + ["--exclude", "${DIRECT_ONLY_MODULE}"]
    }
    ex.autolinkLibrariesFromCommand(picketRnConfigCommand)`;

function configureSettingsGradle(source) {
  const text = source.replace(/\r\n/g, "\n");
  if (text.includes(settingsBlock) && text.includes(rnCommandBlock)) return source;

  if (text.includes(marker)) {
    if (!text.includes(legacySettingsBlock) || !text.includes(legacyRnCommandBlock)) {
      throw new Error("Unrecognized Picket settings.gradle block; re-run prebuild with --clean.");
    }
    return text.replace(legacySettingsBlock, settingsBlock).replace(legacyRnCommandBlock, rnCommandBlock);
  }

  const pluginsBlock = `plugins {
  id("com.facebook.react.settings")
  id("expo-autolinking-settings")
}`;
  if (!source.includes(pluginsBlock)) {
    throw new Error("Unable to locate Expo settings plugins block.");
  }

  source = source.replace(pluginsBlock, `${pluginsBlock}

${settingsBlock}`);

  const rnCommand = "ex.autolinkLibrariesFromCommand(expoAutolinking.rnConfigCommand)";
  if (!source.includes(rnCommand)) {
    throw new Error("Unable to locate Expo React Native autolinking command.");
  }
  return source.replace(rnCommand, rnCommandBlock);
}

function blockPermission(manifest, permission) {
  const permissions = (manifest["uses-permission"] ??= []);
  const existing = permissions.find(
    (entry) => entry.$?.["android:name"] === permission,
  );
  if (existing) {
    existing.$["tools:node"] = "remove";
    return;
  }
  permissions.push({
    $: { "android:name": permission, "tools:node": "remove" },
  });
}

// Merged in from picket-app-updates; Google Play builds must never carry them.
const INSTALL_PERMISSIONS = [
  "android.permission.REQUEST_INSTALL_PACKAGES",
  "android.permission.UPDATE_PACKAGES_WITHOUT_USER_ACTION",
];

function configureManifest(manifest, isPlayBuild) {
  manifest.$ ??= {};
  manifest.$["xmlns:tools"] ??= "http://schemas.android.com/tools";
  if (isPlayBuild) for (const permission of INSTALL_PERMISSIONS) blockPermission(manifest, permission);
  else manifest["uses-permission"] = (manifest["uses-permission"] ?? []).filter(entry =>
    !(INSTALL_PERMISSIONS.includes(entry.$?.["android:name"]) && entry.$?.["tools:node"] === "remove"));
  blockPermission(manifest, "android.permission.SYSTEM_ALERT_WINDOW");
  return manifest;
}

function configureAppBuildGradle(source) {
  const marker = "// Picket update channel bundle input";
  if (source.includes(marker)) return source;
  return source + `\n${marker}\ntasks.configureEach { task ->\n  if (task.name.startsWith("createBundle") && task.name.endsWith("JsAndAssets")) {\n    task.inputs.property("picketPlayBuild", providers.environmentVariable("PICKET_PLAY_BUILD").getOrElse("0"))\n  }\n}\n`;
}

module.exports = function withPlayStoreBuild(config) {
  config = withSettingsGradle(config, (mod) => {
    if (mod.modResults.language !== "groovy") return mod;
    mod.modResults.contents = configureSettingsGradle(mod.modResults.contents);
    return mod;
  });

  config = withAppBuildGradle(config, mod => {
    mod.modResults.contents = configureAppBuildGradle(mod.modResults.contents);
    return mod;
  });
  return withAndroidManifest(config, (mod) => {
    configureManifest(mod.modResults.manifest, playBuild);
    return mod;
  });
};

module.exports.configureSettingsGradle = configureSettingsGradle;
module.exports.configureManifest = configureManifest;
module.exports.configureAppBuildGradle = configureAppBuildGradle;
